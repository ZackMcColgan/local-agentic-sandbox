import { describe, it } from "node:test";
import assert from "node:assert/strict";
import {
  REVIEWER_GATE_STAGE3_DEFAULT,
  isReviewerGateStage3Enabled,
  runMechanicalChecks,
  composeReviewerPrompt,
  evaluateReviewerGate,
  recordAuditComparison,
  createAgreementLedger,
  isMergeAuthorized,
  type MechanicalCheckInput,
  type ReviewerVerdict,
} from "../lib/board/reviewerGate";

const CLEAN_DIFF = [
  "diff --git a/web-ui/lib/board/reviewerGate.ts b/web-ui/lib/board/reviewerGate.ts",
  "new file mode 100644",
  "index 0000000..1111111",
  "--- /dev/null",
  "+++ b/web-ui/lib/board/reviewerGate.ts",
  "@@ -0,0 +1,3 @@",
  "+export function evaluate() {",
  "+  return true;",
  "+}",
].join("\n");

function makeCleanInput(overrides: Partial<MechanicalCheckInput> = {}): MechanicalCheckInput {
  return {
    diff: CLEAN_DIFF,
    allowlist: ["web-ui/lib/board/reviewerGate.ts", "web-ui/tests/reviewerGate.test.ts"],
    commitSubjects: ["Add reviewer gate mechanical checks"],
    branchName: "feature/reviewer-gate",
    ...overrides,
  };
}

describe("reviewerGate — mechanical checks", () => {
  it("passes a clean diff within allowlist, clean hygiene, and no weakened tests", () => {
    const result = runMechanicalChecks(makeCleanInput());
    assert.equal(result.verdict, "PASS");
    assert.equal(result.failures.length, 0);
  });

  it("FAILs an allowlist violation with the offending file named", () => {
    const diff = [
      "diff --git a/web-ui/lib/board/boardStore.ts b/web-ui/lib/board/boardStore.ts",
      "index 1111111..2222222 100644",
      "--- a/web-ui/lib/board/boardStore.ts",
      "+++ b/web-ui/lib/board/boardStore.ts",
      "@@ -1,1 +1,2 @@",
      " export const x = 1;",
      "+export const y = 2;",
    ].join("\n");

    const result = runMechanicalChecks(makeCleanInput({ diff }));
    assert.equal(result.verdict, "FAIL");
    assert.ok(
      result.failures.some(
        (f) => f.check === "allowlist" && f.evidence.includes("web-ui/lib/board/boardStore.ts"),
      ),
    );
  });

  it("FAILs when a banned string appears in added lines", () => {
    const diff = [
      "diff --git a/web-ui/lib/board/reviewerGate.ts b/web-ui/lib/board/reviewerGate.ts",
      "--- a/web-ui/lib/board/reviewerGate.ts",
      "+++ b/web-ui/lib/board/reviewerGate.ts",
      "@@ -1,1 +1,2 @@",
      " export const x = 1;",
      "+// generated by claude",
    ].join("\n");

    const result = runMechanicalChecks(makeCleanInput({ diff }));
    assert.equal(result.verdict, "FAIL");
    assert.ok(result.failures.some((f) => f.check === "hygiene" && f.evidence.includes("claude")));
  });

  it("FAILs when a banned string appears in a commit subject", () => {
    const result = runMechanicalChecks(
      makeCleanInput({ commitSubjects: ["Fix bug with codex"] }),
    );
    assert.equal(result.verdict, "FAIL");
    assert.ok(result.failures.some((f) => f.check === "hygiene" && f.evidence.includes("codex")));
  });

  it("FAILs when a banned string appears in the branch name", () => {
    const result = runMechanicalChecks(
      makeCleanInput({ branchName: "feature/gemini-reviewer" }),
    );
    assert.equal(result.verdict, "FAIL");
    assert.ok(result.failures.some((f) => f.check === "hygiene" && f.evidence.includes("gemini")));
  });

  for (const term of ["hydrogen", "argon", "sandy"]) {
    it(`FAILs when ${term} appears in added lines`, () => {
      const diff = [
        "diff --git a/web-ui/lib/board/reviewerGate.ts b/web-ui/lib/board/reviewerGate.ts",
        "--- a/web-ui/lib/board/reviewerGate.ts",
        "+++ b/web-ui/lib/board/reviewerGate.ts",
        "@@ -1,1 +1,2 @@",
        " export const x = 1;",
        `+// note mentioning ${term}`,
      ].join("\n");

      const result = runMechanicalChecks(makeCleanInput({ diff }));
      assert.equal(result.verdict, "FAIL");
      assert.ok(result.failures.some((f) => f.check === "hygiene" && f.evidence.includes(term)));
    });

    it(`FAILs when ${term} appears in a commit subject`, () => {
      const result = runMechanicalChecks(
        makeCleanInput({ commitSubjects: [`Fix issue in ${term} pass`] }),
      );
      assert.equal(result.verdict, "FAIL");
      assert.ok(result.failures.some((f) => f.check === "hygiene" && f.evidence.includes(term)));
    });

    it(`FAILs when ${term} appears in the branch name`, () => {
      const result = runMechanicalChecks(
        makeCleanInput({ branchName: `feature/${term}-fix` }),
      );
      assert.equal(result.verdict, "FAIL");
      assert.ok(result.failures.some((f) => f.check === "hygiene" && f.evidence.includes(term)));
    });
  }

  it("FAILs when a test file is deleted", () => {
    const diff = [
      "diff --git a/web-ui/tests/reviewerGate.test.ts b/web-ui/tests/reviewerGate.test.ts",
      "deleted file mode 100644",
      "index 1111111..0000000",
      "--- a/web-ui/tests/reviewerGate.test.ts",
      "+++ /dev/null",
      "@@ -1,2 +0,0 @@",
      "-import assert from 'node:assert/strict';",
      "-assert.equal(1, 1);",
    ].join("\n");

    const result = runMechanicalChecks(makeCleanInput({ diff }));
    assert.equal(result.verdict, "FAIL");
    assert.ok(
      result.failures.some(
        (f) => f.check === "no-test-weakened" && f.evidence.includes("reviewerGate.test.ts"),
      ),
    );
  });

  it("FAILs when a test file has assertions removed (assertion count drops)", () => {
    const diff = [
      "diff --git a/web-ui/tests/reviewerGate.test.ts b/web-ui/tests/reviewerGate.test.ts",
      "index 1111111..2222222 100644",
      "--- a/web-ui/tests/reviewerGate.test.ts",
      "+++ b/web-ui/tests/reviewerGate.test.ts",
      "@@ -1,3 +1,1 @@",
      " assert.equal(1, 1);",
      "-assert.equal(2, 2);",
      "-expect(true).toBe(true);",
    ].join("\n");

    const result = runMechanicalChecks(makeCleanInput({ diff }));
    assert.equal(result.verdict, "FAIL");
    assert.ok(
      result.failures.some(
        (f) => f.check === "no-test-weakened" && f.evidence.includes("reviewerGate.test.ts"),
      ),
    );
  });
});

describe("reviewerGate — verdict combination & shadow mode", () => {
  it("defaults Stage 3 flag to OFF", () => {
    assert.equal(REVIEWER_GATE_STAGE3_DEFAULT, false);
    assert.equal(isReviewerGateStage3Enabled(), false);
  });

  it("issues a fresh reviewer thread and passes only when BOTH mechanical and reviewer PASS", async () => {
    let issuedBrief = "";
    const result = await evaluateReviewerGate({
      itemId: "item-24",
      brief: "Implement reviewer gate",
      mechanicalInput: makeCleanInput(),
      issueReviewerThread: async ({ brief }) => {
        issuedBrief = brief;
        return {
          threadId: "rev-thread-1",
          verdict: "PASS",
          evidence: ["All acceptance criteria verified"],
        };
      },
    });

    assert.ok(issuedBrief.includes("Implement reviewer gate"));
    assert.equal(result.verdict, "PASS");
    assert.equal(result.shadowMode, true);
    assert.equal(result.mergeAuthorized, false);
  });

  it("FAILs overall when mechanical passes but reviewer FAILs", async () => {
    const result = await evaluateReviewerGate({
      itemId: "item-24",
      brief: "Implement reviewer gate",
      mechanicalInput: makeCleanInput(),
      issueReviewerThread: async () => ({
        threadId: "rev-thread-2",
        verdict: "FAIL",
        evidence: ["Missing error path guard"],
      }),
    });

    assert.equal(result.verdict, "FAIL");
    assert.equal(result.mergeAuthorized, false);
  });

  it("never treats a reviewer verdict as merge authorization while Stage 3 is OFF", () => {
    const authorized = isMergeAuthorized({
      stage3Enabled: false,
      ciAllGreen: true,
      reviewerGateVerdict: "PASS",
      finishVerificationClean: true,
    });
    assert.equal(authorized, false);
  });

  it("authorizes merge only when Stage 3 is ON and CI + reviewer + finish-verification are all clean", () => {
    assert.equal(
      isMergeAuthorized({
        stage3Enabled: true,
        ciAllGreen: true,
        reviewerGateVerdict: "PASS",
        finishVerificationClean: true,
      }),
      true,
    );
    assert.equal(
      isMergeAuthorized({
        stage3Enabled: true,
        ciAllGreen: true,
        reviewerGateVerdict: "FAIL",
        finishVerificationClean: true,
      }),
      false,
    );
  });

  it("composes a fresh reviewer prompt containing brief, diff, and standing audit scope", () => {
    const prompt = composeReviewerPrompt("Item brief text", CLEAN_DIFF);
    assert.ok(prompt.includes("Item brief text"));
    assert.ok(prompt.includes(CLEAN_DIFF));
    assert.ok(prompt.toLowerCase().includes("fresh"));
  });
});

describe("reviewerGate — agreement & escape accounting", () => {
  it("tracks agreement rate and records driver-blocked / reviewer-passed PRs as escapes and test cases", () => {
    let ledger = createAgreementLedger();
    for (let i = 1; i <= 9; i++) {
      ledger = recordAuditComparison(ledger, {
        prNumber: i,
        driverVerdict: "PASS",
        reviewerVerdict: "PASS",
        diff: CLEAN_DIFF,
      });
    }
    ledger = recordAuditComparison(ledger, {
      prNumber: 10,
      driverVerdict: "FAIL",
      reviewerVerdict: "PASS",
      reason: "Driver caught subtle regression",
      diff: CLEAN_DIFF,
    });

    assert.equal(ledger.totalPrs, 10);
    assert.equal(ledger.agreements, 9);
    assert.equal(ledger.agreementRate, 0.9);
    assert.equal(ledger.escapes.length, 1);
    assert.equal(ledger.escapes[0].prNumber, 10);
    assert.equal(ledger.reviewerTestCases.length, 1);
    assert.equal(ledger.reviewerTestCases[0].prNumber, 10);
    assert.equal(ledger.stage3Eligible, false);
  });

  it("marks Stage 3 eligible only when >=95% agreement over >=10 PRs with zero escapes", () => {
    let ledger = createAgreementLedger();
    for (let i = 1; i <= 10; i++) {
      ledger = recordAuditComparison(ledger, {
        prNumber: i,
        driverVerdict: "PASS",
        reviewerVerdict: "PASS",
        diff: CLEAN_DIFF,
      });
    }
    assert.equal(ledger.agreementRate, 1);
    assert.equal(ledger.escapes.length, 0);
    assert.equal(ledger.stage3Eligible, true);
  });
});
